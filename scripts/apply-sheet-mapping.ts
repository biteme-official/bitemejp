interface MappingEntry {
  jp_numeric_id: string;
  jp_title: string;
  jp_handle: string;
  kr_product_cd: string | null;
  kr_name: string | null;
  confidence: string;
}

const mappingPath = join(DATA_DIR, 'product-mapping.json');
const existing: MappingEntry[] = JSON.parse(readFileSync(mappingPath, 'utf-8'));

let updated = 0;
let unchanged = 0;

const result = existing.map((entry) => {
  const sheetKr = SHEET_MAPPING[entry.jp_numeric_id];

  // 스프레드시트에 없는 JP ID면 기존 유지
  if (!(entry.jp_numeric_id in SHEET_MAPPING)) {
    unchanged++;
    return entry;
  }

  const newKr = sheetKr ?? null;
  const changed = entry.kr_product_cd !== newKr;
  if (changed) updated++;
  else unchanged++;

  return {
    ...entry,
    kr_product_cd: newKr,
    kr_name: null, // 시트엔 이름 없음
    confidence: newKr ? 'confirmed' : 'no_match',
  };
});

writeFileSync(mappingPath, JSON.stringify(result, null, 2), 'utf-8');
console.log(`✓ 업데이트: ${updated}개 변경, ${unchanged}개 유지`);

// 크롤링 필요한 KR 코드 출력
const needScrape = [...new Set(
  result
    .filter(e => e.kr_product_cd)
    .map(e => e.kr_product_cd!)
)];
console.log(`\n매핑된 KR 코드: ${needScrape.length}개`);
